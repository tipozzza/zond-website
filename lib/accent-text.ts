/**
 * Цвета направлений (оранжевый, жёлтый, зелёный, голубой) хороши для заливок,
 * рамок и иконок, но как цвет ТЕКСТА на белом они нечитаемы: контраст
 * 1,5–2,8:1 при норме WCAG AA 4,5:1 для обычного текста.
 *
 * Здесь — те же оттенки, затемнённые до ≥4,8:1 на белом. Использовать для
 * ссылок и подписей на светлом фоне; для фонов и рамок оставлять исходный цвет.
 */
const TEXT_ON_WHITE: Record<string, string> = {
  "#F57C28": "#BB5209", // наружная реклама: 2,7:1 → 4,9:1
  "#FFCC00": "#8A6E00", // широкоформатная печать: 1,5:1 → 4,9:1
  "#7CB342": "#557B2D", // производство: 2,5:1 → 4,9:1
  "#3FA3D9": "#2179A8", // выставочные экспозиции: 2,8:1 → 4,8:1
};

/** Цвет для текста на белом фоне по цвету направления. Тёмные цвета — как есть. */
export function accentText(hex: string): string {
  return TEXT_ON_WHITE[hex.toUpperCase()] ?? hex;
}
